// Att48 返回指导书附件 1 的 att48 实例（48 座美国州府，ATT 距离，最优 10628）。
func Att48() *Instance {
	cities := make([]City, len(att48Coords))
	for i, c := range att48Coords {
		cities[i] = City{ID: i, X: c[0], Y: c[1]}
	}
	return &Instance{
		Name:        "att48",
		EdgeType:    "att",
		Cities:      cities,
		Optimal:     10628,
		OptimalTour: Att48OptimalTour(),
	}
}

